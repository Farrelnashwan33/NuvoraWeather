class I18nStore {
	current = $state('id'); // Default Indonesian

	init() {
		if (typeof localStorage !== 'undefined') {
			const saved = localStorage.getItem('nuvora-lang');
			if (saved && (saved in translations || LANGUAGES.some(l => l.code === saved))) {
				this.current = saved;
			}
		}
	}

	setLanguage(langCode) {
		this.current = langCode;
		if (typeof localStorage !== 'undefined') {
			localStorage.setItem('nuvora-lang', langCode);
		}
		if (typeof document !== 'undefined') {
			const langObj = LANGUAGES.find(l => l.code === langCode);
			document.documentElement.dir = langObj?.dir || 'ltr';
			document.documentElement.lang = langCode;
		}
	}

	t(key, fallback = '') {
		const dict = translations[this.current] || translations['en'] || translations['id'];
		if (dict && dict[key]) {
			return dict[key];
		}
		if (translations['en'] && translations['en'][key]) {
			return translations['en'][key];
		}
		if (translations['id'] && translations['id'][key]) {
			return translations['id'][key];
		}
		return fallback || key;
	}

	translateCondition(condStr) {
		if (!condStr) return '';
		const normalized = condStr.toLowerCase().trim();
		const key = CONDITION_KEYS[normalized];
		if (key) {
			return this.t(key, condStr);
		}
		return condStr;
	}

	translateStatus(statusStr) {
		if (!statusStr) return '';
		const normalized = String(statusStr).toLowerCase().trim();
		const key = STATUS_KEYS[normalized];
		if (key && STATUS_I18N[key]) {
			return STATUS_I18N[key][this.current] || STATUS_I18N[key]['en'] || STATUS_I18N[key]['id'] || statusStr;
		}
		return statusStr;
	}

	translateDayLabel(dayLabel) {
		if (!dayLabel) return '';
		const lower = dayLabel.toLowerCase();
		if (lower === 'today' || lower === 'hari ini') return this.t('day_today', 'Today');
		if (lower === 'tomorrow' || lower === 'besok') return this.t('day_tomorrow', 'Tomorrow');
		return dayLabel;
	}

	getGreeting() {
		const hour = new Date().getHours();
		if (hour >= 5 && hour < 12) return this.t('greeting_morning', 'Selamat Pagi');
		if (hour >= 12 && hour < 17) return this.t('greeting_afternoon', 'Selamat Siang');
		if (hour >= 17 && hour < 21) return this.t('greeting_evening', 'Selamat Sore');
		return this.t('greeting_night', 'Selamat Malam');
	}

	formatDate(dateObj = new Date()) {
		try {
			const locale = this.current === 'id' ? 'id-ID' : this.current;
			return new Intl.DateTimeFormat(locale, {
				weekday: 'long',
				month: 'short',
				day: 'numeric'
			}).format(dateObj);
		} catch (e) {
			return new Date().toLocaleDateString();
		}
	}

	get activeLangObj() {
		return LANGUAGES.find(l => l.code === this.current) || LANGUAGES[0];
	}
}

export const i18n = new I18nStore();
export const t = (key, fallback = '') => i18n.t(key, fallback);
